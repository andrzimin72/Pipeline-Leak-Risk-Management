# 4. Main Layout: Tabbed Interface
# ==============================================================================
tab_ops, tab_risk, tab_eam = st.tabs(["📡 Operational Control", "️ Executive Risk Heatmap", "️ Autonomous Actions & EAM"])

# --- TAB 1: Operational Control ---
with tab_ops:
    col1, col2 = st.columns([2, 1])
    with col1:
        st.subheader(" Live Event Log")
        if alerts:
            df_data = [{"Time": a["payload"]["timestamp"][:19], "Node": a["payload"]["node_id"], 
                        "Decision": a["payload"]["decision"], "Confidence": f"{a['payload']['final_confidence']*100:.1f}%"} 
                       for a in reversed(alerts)]
            st.dataframe(pd.DataFrame(df_data), use_container_width=True, hide_index=True)
        else:
            st.info("Waiting for edge alerts...")

        st.subheader("️ 11-Modal Sensor Fusion Analysis (Latest Event)")
        if alerts:
            scores = alerts[-1]["payload"]["scores"]
            categories = ['Pressure', 'Coriolis Mass', 'Fiber DTS', 'Acoustic', 'Soil Moisture', 
                          'Point Temp', 'Capacitance', 'Corrosion', 'Vibration', 'Std Flow', 'Physics Residual']
            keys = ['pressure', 'coriolis_mass', 'fiber_dts', 'acoustic', 'soil_moisture', 
                    'point_temp', 'capacitance', 'corrosion', 'vibration', 'standard_flow', 'physics_residual']
            values = [scores.get(k, 0) for k in keys]
            
            fig = go.Figure(data=go.Scatterpolar(r=values + [values[0]], theta=categories + [categories[0]],
                fill='toself', fillcolor='rgba(255, 99, 71, 0.2)', line=dict(color='tomato', width=3)))
            fig.update_layout(polar=dict(radialaxis=dict(visible=True, range=[0, 1])), showlegend=False, height=500, paper_bgcolor='rgba(0,0,0,0)', plot_bgcolor='rgba(0,0,0,0)', font=dict(color='white'))
            st.plotly_chart(fig, use_container_width=True)
        else:
            st.info("Waiting for edge alerts to generate radar chart...")

    with col2:
        st.subheader("📄 Latest PHMSA AI Report")
        if alerts:
            latest = alerts[-1]
            st.markdown(f"**Event ID:** `{latest['payload']['event_id']}`")
            st.markdown(f"**Decision:** `{latest['payload']['decision']}`")
            st.divider()
            st.markdown(latest["report"]["report_text"].replace("\n", "  \n"))
        else:
            st.info("Waiting for edge alerts...")

# --- TAB 2: Executive Risk Heatmap ---
with tab_risk:
    st.subheader("Geospatial Dynamic Risk Distribution")
    
    if risk_data:
        # Filter out work order dicts to get pure node data
        nodes = [r for r in risk_data if "node_id" in r]
        df_risk = pd.DataFrame(nodes)
        
        colorscale = [[0.0, 'rgb(0, 200, 83)'], [0.33, 'rgb(255, 235, 59)'], [0.66, 'rgb(255, 152, 0)'], [1.0, 'rgb(244, 67, 54)']]

        fig = go.Figure()
        # Pipeline Route
        if not df_risk.empty:
            fig.add_trace(go.Scattergeo(lon=df_risk['lon'], lat=df_risk['lat'], mode='lines',
                line=dict(width=2, color='rgba(100, 100, 100, 0.5)'), hoverinfo='skip', showlegend=False))
            
            # Risk Nodes
            fig.add_trace(go.Scattergeo(lon=df_risk['lon'], lat=df_risk['lat'], mode='markers+text',
                text=df_risk['node_id'], textposition="top center", textfont=dict(size=8, color='white'),
                marker=dict(size=df_risk['dynamic_risk_index'] / 2 + 5, color=df_risk['dynamic_risk_index'],
                colorscale=colorscale, cmin=0, cmax=100, line=dict(width=1, color='white'), opacity=0.9,
                colorbar=dict(title="Dynamic Risk Index (DRI)", x=1.02, thickness=15)),
                hovertemplate="<b>%{text}</b><br>Risk Tier: %{customdata[0]}<br>DRI: %{customdata[1]}<br>PoF: %{customdata[2]}%<br>CoF: %{customdata[3]}%<extra></extra>",
                customdata=df_risk[['risk_tier', 'dynamic_risk_index', 'pof', 'cof']], name='Sensor Nodes'))

        fig.update_layout(geo=dict(scope='usa', projection=dict(type='albers usa'), showland=True, landcolor='rgb(30, 30, 30)',
            showocean=True, oceancolor='rgb(10, 10, 20)'), paper_bgcolor='rgba(0,0,0,0)', plot_bgcolor='rgba(0,0,0,0)',
            font=dict(color='white'), height=650, margin=dict(l=0, r=0, t=30, b=0))
        st.plotly_chart(fig, use_container_width=True)
    else:
        st.info("No risk data available. Trigger an alert to generate risk assessments.")

# --- TAB 3: Autonomous Actions & EAM ---
