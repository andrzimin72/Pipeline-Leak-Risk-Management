API_BASE_URL = "http://localhost:8000"

# ==============================================================================
# 2. Data Fetching (API with Mock Fallback)
# ==============================================================================
def fetch_data():
    """Fetches data from API, falls back to local JSON, then to mock data."""
    alerts, scada_logs, risk_data = [], [], []
    
    try:
        # Try fetching from API
        resp_alerts = requests.get(f"{API_BASE_URL}/api/v1/risk/nodes", timeout=2) # Using risk endpoint to check API
        # In a real app, we'd have specific endpoints for alerts/logs. 
        # For this prototype, we read the local files generated by the API.
    except:
        pass

    # Read local files generated by the API
    data_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), '../data'))
    
    def load_json(filename):
        path = os.path.join(data_dir, filename)
        if os.path.exists(path):
            with open(path, "r") as f:
                try: return json.load(f)
                except: return []
        return []

    alerts = load_json("alerts.json")
    scada_logs = load_json("scada_logs.json")
    risk_data = load_json("risk_assessments.json")
    
    # If completely empty, generate mock data for the demo
    if not alerts and not risk_data:
        st.toast("API offline. Loading Executive Mock Data...", icon="⚠️")
        # Mock Risk Data for Heatmap
        np.random.seed(42)
        for i in range(25):
            pof = np.random.uniform(70, 95) if 14 <= i <= 17 else np.random.uniform(5, 25)
            cof = np.random.uniform(80, 100) if 14 <= i <= 17 else np.random.uniform(10, 40)
            dri = (pof * cof) / 100.0
            tier = "CRITICAL" if dri >= 75 else "LOW"
            risk_data.append({
                "node_id": f"NODE-{100+i}", "lat": 31.99 - (i*0.1), "lon": -102.07 + (i*0.3),
                "pof": pof, "cof": cof, "dynamic_risk_index": dri, "risk_tier": tier,
                "mitigation_plan": [f"Tier {tier} protocol active."] if tier == "CRITICAL" else ["Standard monitoring."]
            })
            
    return alerts, scada_logs, risk_data

alerts, scada_logs, risk_data = fetch_data()

